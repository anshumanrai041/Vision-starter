import numpy as np
import matplotlib.pyplot as plt 
height, width=100 , 100
x=np.linspace(0,255,width)
y=np.linspace(0,255,height)
xx, yy =np.meshgrid(x,y)
img_red=xx.astype(np.uint8)

img_green=yy.astype(np.uint8)
img_blue=np.abs(xx-yy).astype(np.uint8)
img_rgb=np.stack([img_red , img_green ,img_blue], axis=-1)
r=img_rgb[:,:,0].astype(np.float32)
g=img_rgb[:,:,1].astype(np.float32)
b=img_rgb[:,:,2].astype(np.float32)
gray=(0.299*r+0.587*g+0.114*b).astype(np.uint8)
hist_r=np.bincount(img_rgb[:,:,0].ravel(),minlength=256)
hist_g=np.bincount(img_rgb[:,:,1].ravel(),minlength=256)
hist_b=np.bincount(img_rgb[:,:,2].ravel(),minlength=256)
hist_gray=np.bincount(gray.ravel() , minlength=256)
plt.figure(figsize=(12,6))
plt.subplot(1,2,1)
plt.imshow(img_rgb)
plt.title("synthetic RGB image")
plt.axis("off")
plt.subplot(1,2,2)
plt.plot(hist_r ,color="red", label="Red Channel" , alpha=0.8)
plt.plot(hist_g ,color="green", label="green Channel" , alpha=0.8)
plt.plot(hist_b ,color="blue", label="blue Channel" , alpha=0.8)
plt.plot(hist_gray , color="black", label="Grayscale Luma" , linestyle="--", linewidth=2)
plt.title("channel intensity histograms (0-255)")
plt.xlabel("Pixel intensity value")
plt.ylabel("pixel Count (frequency)")
plt.legend()
plt.grid(True , linestyle=":" ,alpha=0.6)
plt.tight_layout()
plt.show()
